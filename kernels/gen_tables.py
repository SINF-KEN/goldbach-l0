#!/usr/bin/env python3
"""Generates kernels/goldbach_tables.h, the constant tables of goldbach.cl.

The tables are pure functions of the multiplier wheel 30030 = 2*3*5*7*11*13
and of the redundant-mark residue sets {17, 19, 23, 29} / {31, 37, 41, 43}.
goldbach.cl declares each table (type, size, comment) and initialises it from
the macro <NAME>_INIT defined here; ocloc needs `-I kernels` (CMake, ci.yml
and ci/experiment.py pass it).

  python3 kernels/gen_tables.py           # rewrite kernels/goldbach_tables.h
  python3 kernels/gen_tables.py --check   # exit 1 if the file is stale (ctest)
"""
import math
import pathlib
import sys

W = 30030
OUT = pathlib.Path(__file__).with_name("goldbach_tables.h")

# M[w]: the odd multipliers coprime to W, ascending (5760 of them)
M = [m for m in range(1, W, 2) if math.gcd(m, W) == 1]
N = len(M)
assert N == 5760


def whl_idx():
    idx = [0xFFFF] * W
    for w, m in enumerate(M):
        idx[m] = w
    return idx


def whl_inv():
    return [pow(r, -1, W) if math.gcd(r, W) == 1 else 0 for r in range(W)]


def whl_step():
    return [((M[w + 1] if w + 1 < N else W + M[0]) - M[w]) // 2 for w in range(N)]


def cp15015():
    """Bit x of the 470-word bitmap <-> gcd(x, 15015) == 1 (x < 15015)."""
    words = [0] * 470
    for x in range(15015):
        if math.gcd(x, 15015) == 1:
            words[x >> 5] |= 1 << (x & 31)
    return words


def whl_sf():
    """WHL_STEP[w] | (M[w] mod r_i) << (4 + 6 i), r = 17, 19, 23, 29; padded with entries 0..7."""
    st = whl_step()
    t = [st[w] | sum((M[w] % r) << (4 + 6 * i) for i, r in enumerate((17, 19, 23, 29))) for w in range(N)]
    return t + t[:8]


def whl_sf2():
    """sum (M[w] mod r_i) << 7 i, r = 31, 37, 41, 43; padded with entries 0..7."""
    t = [sum((M[w] % r) << (7 * i) for i, r in enumerate((31, 37, 41, 43))) for w in range(N)]
    return t + t[:8]


def skr_mr(rs):
    """[o_i + (p mod r_i) r_i + (q mod r_i)] = q p^-1 mod r_i (0 where p = 0 mod r_i)."""
    out = []
    for r in rs:
        for p in range(r):
            for q in range(r):
                out.append(q * pow(p, -1, r) % r if p else 0)
    return out


def mq_rk():
    """(bitmap, rank) per 32 odd residues 2 j + 1, j < 15015."""
    out, rank = [], 0
    for b in range(470):
        bits = 0
        for k in range(32):
            j = 32 * b + k
            if j < 15015 and math.gcd(2 * j + 1, W) == 1:
                bits |= 1 << k
        out.append((bits, rank))
        rank += bin(bits).count("1")
    return out


def body(vals, fmt, per_line):
    lines = [", ".join(fmt(v) for v in vals[i:i + per_line]) for i in range(0, len(vals), per_line)]
    return "{ \\\n    " + ", \\\n    ".join(lines) + " }"


def render():
    dec = str
    hx = lambda v: f"0x{v:07X}u"
    parts = [
        ("WHL_IDX", whl_idx(), dec, 24),
        ("WHL_INV", whl_inv(), dec, 24),
        ("WHL_STEP", whl_step(), dec, 40),
        ("CP15015", cp15015(), lambda v: f"0x{v:08X}u", 8),
        ("WHL_SF", whl_sf(), hx, 10),
        ("SKR_MR", skr_mr((17, 19, 23, 29)), dec, 32),
        ("WHL_SF2", whl_sf2(), hx, 10),
        ("SKR_MR2", skr_mr((31, 37, 41, 43)), dec, 40),
        ("MQ_RK", mq_rk(), lambda v: f"(uint2)(0x{v[0]:08X}u, {v[1]}u)", 4),
        ("WHL_M", M, dec, 16),
    ]
    out = ["// GENERATED by kernels/gen_tables.py — do not edit; rerun the script.",
           "// Constant tables of kernels/goldbach.cl (declared there, defined here).",
           "#ifndef GOLDBACH_TABLES_H", "#define GOLDBACH_TABLES_H", ""]
    for name, vals, fmt, per in parts:
        out.append(f"// {len(vals)} entries")
        out.append(f"#define {name}_INIT {body(vals, fmt, per)}")
        out.append("")
    out.append("#endif")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv[1:]:
        if OUT.read_text() != text:
            print(f"{OUT} is stale: rerun python3 kernels/gen_tables.py", file=sys.stderr)
            sys.exit(1)
        print(f"{OUT} up to date")
    else:
        OUT.write_text(text)
